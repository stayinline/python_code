	CREATE TABLE "RPTDW"."DIM_CALENDAR"
	( "FACTORY" VARCHAR2(255),
	"TIME_TYPE" VARCHAR2(255),
	"TIME_KEY" VARCHAR2(255),
	"SHIFT_START_TIMEKEY" VARCHAR2(255),
	"SHIFT_END_TIMEKEY" VARCHAR2(255),
	"DATE_START_TIMEKEY" VARCHAR2(255),
	"DATE_END_TIMEKEY" VARCHAR2(255),
	"SHIFT_TIMEKEY" VARCHAR2(255),
	"SHIFT_NAME" VARCHAR2(255),
	"DATE_TIMEKEY" VARCHAR2(255),
	"WEEK_TIMEKEY" VARCHAR2(255),
	"MONTH_TIMEKEY" VARCHAR2(255),
	"QUARTER_TIMEKEY" VARCHAR2(255),
	"YEAR_TIMEKEY" VARCHAR2(255),
	"INTERFACE_TIME" TIMESTAMP (6)
	) SEGMENT CREATION IMMEDIATE
	PCTFREE 10 PCTUSED 40 INITRANS 1 MAXTRANS 255
	NOCOMPRESS LOGGING
	TABLESPACE "DWD_MES_18M_DAT" ;

	CREATE INDEX "RPTDW"."IDX03_DIM_CALENDAR" ON "RPTDW"."DIM_CALENDAR" ("SHIFT_START_TIMEKEY", "SHIFT_END_TIMEKEY", "TIME_KEY", "TIME_TYPE")
	PCTFREE 10 INITRANS 2 MAXTRANS 255 COMPUTE STATISTICS NOLOGGING
	TABLESPACE "DWD_MES_18M_IDX" ;

	CREATE INDEX "RPTDW"."IDX01_DIM_CALENDAR" ON "RPTDW"."DIM_CALENDAR" ("TIME_KEY", "TIME_TYPE")
	PCTFREE 10 INITRANS 2 MAXTRANS 255 COMPUTE STATISTICS NOLOGGING
	TABLESPACE "DWD_MES_18M_IDX" ;

	COMMENT ON COLUMN RPTDW.DIM_CALENDAR.FACTORY IS '厂别';
	COMMENT ON COLUMN RPTDW.DIM_CALENDAR.SHIFT_TIMEKEY IS '班别时间：0160806 073000';
	COMMENT ON COLUMN RPTDW.DIM_CALENDAR.DATE_TIMEKEY IS '日期';




