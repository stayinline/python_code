	"RESERVED5" VARCHAR2(32),
	"RESERVED6" VARCHAR2(32),
	"RESERVED7" VARCHAR2(32),
	"RESERVED8" VARCHAR2(32),
	"UPDATE_TIME" DATE,
	PRIMARY KEY ("OBJECT_RRN")
	USING INDEX PCTFREE 10 INITRANS 2 MAXTRANS 255 COMPUTE STATISTICS
	TABLESPACE "ODS_MES_HIS_12M_IDX" ENABLE
	) SEGMENT CREATION IMMEDIATE
	PCTFREE 10 PCTUSED 40 INITRANS 1 MAXTRANS 255
	NOCOMPRESS LOGGING
	TABLESPACE "ODS_MES_HIS_12M_DAT" ;

	COMMENT ON TABLE RPTDW.ODS_MES_CT_INCOMING_CHECK IS '通道等级表';
	COMMENT ON COLUMN RPTDW.ODS_MES_CT_INCOMING_CHECK.OBJECT_RRN IS '对象序列号';
