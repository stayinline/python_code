	"ORG_RRN" NUMBER(19,0),
	"IS_ACTIVE" VARCHAR2(1),
	"CREATED" DATE,
	"CREATED_BY" VARCHAR2(32),
	"UPDATED" DATE,
	"UPDATED_BY" VARCHAR2(32),
	"LOCK_VERSION" NUMBER(19,0),
	"EQUIPMENT_ID" VARCHAR2(32),
	"PANEL_ID" VARCHAR2(32),
	"JUDGE" VARCHAR2(32),
	"RESERVED1" VARCHAR2(32),
	"RESERVED2" VARCHAR2(32),
	"RESERVED3" VARCHAR2(32),
