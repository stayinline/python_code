	COMMENT ON COLUMN RPTDW.ODS_MES_CT_INCOMING_CHECK.IS_ACTIVE IS '是否有效';
	COMMENT ON COLUMN RPTDW.ODS_MES_CT_INCOMING_CHECK.CREATED IS '创建时间';
	COMMENT ON COLUMN RPTDW.ODS_MES_CT_INCOMING_CHECK.CREATED_BY IS '创建者';
	COMMENT ON COLUMN RPTDW.ODS_MES_CT_INCOMING_CHECK.UPDATED IS '更新时间';
	COMMENT ON COLUMN RPTDW.ODS_MES_CT_INCOMING_CHECK.UPDATED_BY IS '更新者';
	COMMENT ON COLUMN RPTDW.ODS_MES_CT_INCOMING_CHECK.LOCK_VERSION IS '锁定版本';
	COMMENT ON COLUMN RPTDW.ODS_MES_CT_INCOMING_CHECK.EQUIPMENT_ID IS '设备ID';
	COMMENT ON COLUMN RPTDW.ODS_MES_CT_INCOMING_CHECK.PANEL_ID IS '屏体ID';
